/**
 * Regenerates ROLES.md from the PERMISSIONS constant so the two cannot drift.
 * Run with `bun run generate:roles`; CI checks the result is committed.
 */
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("src/lib/permissions.ts", "utf8");
const block = source.slice(
  source.indexOf("export const PERMISSIONS = ["),
  source.indexOf("] as const;"),
);
const permissions = [...block.matchAll(/"([^"]+)"/g)].map((m) => m[1]);

if (permissions.length === 0) {
  throw new Error("No permissions parsed from src/lib/permissions.ts");
}

const body = `<!-- Generated by scripts/generate-roles-doc.mjs. Do not edit by hand. -->
# Roles and permissions

These are the permissions that can be granted to a user or a role.

${permissions.map((p) => `- ${p}`).join("\n")}

Role-derived permissions (\`servers::admin\`, \`hetzner:<projectId>:admin\`, …) are
synthesised from group, project and server membership at check time and are not
grantable. See \`src/lib/permissions.ts\`.
`;

writeFileSync("ROLES.md", body);
console.log(`ROLES.md regenerated with ${permissions.length} permissions`);
